export function renderServiceCard(service) {
  const cardElement = document.createElement('article');
  cardElement.className = 'service-card';
  cardElement.setAttribute('data-service-id', service.id);

  cardElement.innerHTML = `
    <div class="service-card-header">
      <div class="service-icon-wrapper">
        ${getServiceIconSvg(service.icon)}
      </div>
      <span class="service-category-badge">${service.category}</span>
    </div>
    <div class="service-card-body">
      <h3 class="service-title">${service.title}</h3>
      <p class="service-description">${service.description}</p>
    </div>
    <div class="service-card-footer">
      <span class="service-trust-tag">
        <svg width="14" height="14" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">
          <polyline points="20 6 9 17 4 12"></polyline>
        </svg>
        Yetkili Servis Kapsamı
      </span>
    </div>
  `;

  return cardElement;
}

export default renderServiceCard;
